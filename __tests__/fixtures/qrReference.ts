/**
 * QR matrices produced by an implementation that is not ours.
 *
 * These were generated with the `qrcode` npm package — which this app
 * deliberately does not depend on — so that `src/sync/qr.ts` is checked
 * against something with no shared code or shared assumptions. Comparing an
 * encoder to itself proves nothing; comparing it module for module to a
 * separate one proves the Reed-Solomon, the interleaving, the placement
 * zigzag, the mask and the format bits are all exactly right.
 *
 * `#` is a dark module, `.` a light one. The quiet zone is not included.
 * Level M throughout, which is what `qr.ts` produces.
 *
 * To regenerate — in a scratch directory, NOT in this project:
 *
 *   npm i qrcode
 *   node -e "const QR=require('qrcode');
 *     const q=QR.create(TEXT,{errorCorrectionLevel:'M'});
 *     const n=q.modules.size;
 *     for(let y=0;y<n;y++){let r='';
 *       for(let x=0;x<n;x++)r+=q.modules.get(y,x)?'#':'.';
 *       console.log(r);}"
 *
 * The two long cases are real pairing codes, produced by `encode()` from
 * fixed 32-byte keys, so the shape being verified is the shape the app
 * actually draws.
 */
